import { openExternalUrl } from './nativeBridge';
/**
 * WhatsApp Daily Sales Report Automation & Dispatcher for AfzPOS.
 * Formats sales data, financial metrics, and low-stock reorder warnings into structured WhatsApp reports.
 */

import { SalesReport, StoreConfig, Product } from '../types/pos';
import { formatCurrency } from './format';

export interface WhatsAppReportOptions {
  report: SalesReport;
  config: StoreConfig;
  lowStockProducts?: Product[];
  periodLabel?: string;
}

/**
 * Format structured sales data into clean, formatted WhatsApp markdown message.
 */
export function formatWhatsAppDailyReport({
  report,
  config,
  lowStockProducts = [],
  periodLabel = 'HARIAN'
}: WhatsAppReportOptions): string {
  const isId = config.language === 'id';
  const now = new Date();
  const dateFormatted = now.toLocaleDateString(isId ? 'id-ID' : 'en-US', {
    weekday: 'long',
    day: 'numeric',
    month: 'short',
    year: 'numeric'
  });
  const timeFormatted = now.toLocaleTimeString(isId ? 'id-ID' : 'en-US', {
    hour: '2-digit',
    minute: '2-digit'
  });

  const currencySym = config.currencySymbol;
  const currencyCd = config.currencyCode;

  const headerTitle = isId
    ? `📊 *LAPORAN PENJUALAN ${periodLabel.toUpperCase()} - AFZPOS*`
    : `📊 *${periodLabel.toUpperCase()} SALES REPORT - AFZPOS*`;

  const topItems = report.productStats.slice(0, 5);

  let message = `${headerTitle}\n`;
  message += `📅 *${isId ? 'Waktu' : 'Timestamp'}*: ${dateFormatted}, ${timeFormatted}\n`;
  message += `🏢 *${isId ? 'Toko' : 'Store'}*: ${config.storeName || 'AfzPOS Terminal'}\n`;
  message += `👤 *${isId ? 'Kasir' : 'Cashier'}*: ${config.defaultCashier || 'Petugas Kasir'}\n`;
  message += `─────────────────────────\n`;

  message += `📈 *${isId ? 'RINGKASAN PENJUALAN' : 'SALES SUMMARY'}*\n`;
  message += `• ${isId ? 'Total Penjualan Kotor' : 'Total Gross Sales'}: *${formatCurrency(report.totalGrossSales, currencySym, currencyCd)}*\n`;
  message += `• ${isId ? 'Total Transaksi' : 'Total Transactions'}: *${report.transactionCount} ${isId ? 'Transaksi' : 'Orders'}*\n`;
  message += `• ${isId ? 'Rata-rata Keranjang' : 'Average Basket'}: ${formatCurrency(report.averageTransactionValue, currencySym, currencyCd)}\n`;
  message += `• ${isId ? 'Total Diskon' : 'Total Discounts'}: -${formatCurrency(report.totalDiscounts, currencySym, currencyCd)}\n`;
  message += `• ${isId ? 'Total Pajak' : 'Total Tax'}: ${formatCurrency(report.totalTax, currencySym, currencyCd)}\n`;
  message += `• ${isId ? 'Pendapatan Bersih' : 'Net Revenue'}: *${formatCurrency(report.totalNetSales, currencySym, currencyCd)}*\n\n`;

  message += `💳 *${isId ? 'METODE PEMBAYARAN' : 'PAYMENT BREAKDOWN'}*\n`;
  message += `• ${isId ? 'Tunai (Cash)' : 'Cash'}: ${formatCurrency(report.paymentMethodTotals.cash, currencySym, currencyCd)}\n`;
  message += `• ${isId ? 'QRIS / E-Wallet' : 'QR / Mobile'}: ${formatCurrency(report.paymentMethodTotals.qr, currencySym, currencyCd)}\n`;
  message += `• ${isId ? 'Kartu Debit/Kredit' : 'Card / Debit'}: ${formatCurrency(report.paymentMethodTotals.card, currencySym, currencyCd)}\n\n`;

  if (topItems.length > 0) {
    message += `🏆 *${isId ? 'PRODUK TERLARIS (TOP SALES)' : 'TOP SELLING PRODUCTS'}*\n`;
    topItems.forEach((item, index) => {
      message += `${index + 1}. *${item.name}*: ${item.quantitySold}x • ${formatCurrency(item.grossRevenue, currencySym, currencyCd)}\n`;
    });
    message += `\n`;
  }

  // Low stock warning section
  if (lowStockProducts.length > 0) {
    message += `⚠️ *${isId ? 'PERINGATAN STOK RENDAH (< BATAS MINIMUM)' : 'LOW STOCK REORDER ALERTS'}*\n`;
    lowStockProducts.slice(0, 5).forEach(prod => {
      const weightDisplay = prod.weight && prod.weightUnit ? ` (${prod.weight}${prod.weightUnit})` : '';
      const threshold = prod.minStockThreshold || 15;
      message += `• *${prod.name}${weightDisplay}* [${prod.sku}]: ${isId ? 'Sisa' : 'Left'} *${prod.stock}* (Min ${threshold}) - ${isId ? 'Segera Reorder!' : 'Restock Required!'}\n`;
    });
    if (lowStockProducts.length > 5) {
      message += `_... ${isId ? `dan ${lowStockProducts.length - 5} produk lainnya` : `and ${lowStockProducts.length - 5} more items`}_\n`;
    }
    message += `\n`;
  }

  message += `─────────────────────────\n`;
  message += `_🤖 ${isId ? 'Laporan harian otomatis dihasilkan oleh sistem AfzPOS Terminal.' : 'Automated daily report generated by AfzPOS Terminal.'}_`;

  return message;
}

/**
 * Clean phone number to ensure standard international WhatsApp format (e.g. +62812... -> 62812...).
 */
export function cleanWhatsAppNumber(phone: string): string {
  let cleaned = phone.replace(/[^\d+]/g, '');
  if (cleaned.startsWith('+')) {
    cleaned = cleaned.substring(1);
  }
  // Convert standard local Indonesian prefix 08... into 628...
  if (cleaned.startsWith('0')) {
    cleaned = '62' + cleaned.substring(1);
  }
  return cleaned;
}

/**
 * Check if the terminal is connected to the internet.
 */
export function isInternetConnected(): boolean {
  return typeof navigator !== 'undefined' ? navigator.onLine : true;
}

/**
 * Dispatches the formatted report to WhatsApp.
 * Opens WhatsApp Web/App with target phone number and pre-filled message text.
 */
export function sendReportToWhatsApp(
  options: WhatsAppReportOptions,
  customPhoneNumber?: string
): { success: boolean; message: string; url?: string } {
  if (!isInternetConnected()) {
    return {
      success: false,
      message: options.config.language === 'id'
        ? 'Perangkat tidak terhubung ke internet. Mohon periksa koneksi Wi-Fi atau data seluler Anda.'
        : 'Device is offline. Please check your internet connectivity.'
    };
  }

  const rawNumber = customPhoneNumber || options.config.whatsappNumber;
  if (!rawNumber || !rawNumber.trim()) {
    return {
      success: false,
      message: options.config.language === 'id'
        ? 'Nomor WhatsApp belum dikonfigurasi di Pengaturan Toko.'
        : 'WhatsApp phone number has not been set in Store Settings.'
    };
  }

  const cleanNumber = cleanWhatsAppNumber(rawNumber);
  if (cleanNumber.length < 8) {
    return {
      success: false,
      message: options.config.language === 'id'
        ? 'Format nomor WhatsApp tidak valid. Masukkan nomor lengkap dengan kode negara (cth: +6281234567890).'
        : 'Invalid WhatsApp phone number. Please include country code (e.g. +6281234567890).'
    };
  }

  const reportText = formatWhatsAppDailyReport(options);
  const encodedText = encodeURIComponent(reportText);
  const whatsappUrl = `https://wa.me/${cleanNumber}?text=${encodedText}`;

  // Buka WhatsApp: lewat intent Android di aplikasi, atau tab baru di browser
  void openExternalUrl(whatsappUrl);

  return {
    success: true,
    message: options.config.language === 'id'
      ? `Laporan berhasil dikirim ke WhatsApp (${cleanNumber})!`
      : `Report dispatched successfully to WhatsApp (${cleanNumber})!`,
    url: whatsappUrl
  };
}
